/** Кингсмув по позам надёжно не отличить: открытый угол бывает и без него (annotator/kingsmove.py). Поэтому
 *  сервер задаёт вопрос, только если долго очень открыт угол; цифр и углов MIRA не называет — ход схватки
 *  пользователю не показываем (эксперт, 2026-10-20). */
const KINGS_DOUBT = 'Кингсмув я по видео могу спутать с обычной борьбой на раскрытых углах.';
const CHECK = ' Сверяю ответы с видео.';
const ackMe = (k: string) => (k === 'yes' ? 'Поняла: ты боролся в кингсмув.' : 'Поняла, ты боролся без кингсмува.');
const ackOpp = (k: string) =>
  k === 'yes' ? 'Поняла: соперник боролся в кингсмув.' : 'Поняла, у соперника кингсмува не было.';

export const Q_KINGS_ME: Question = {
  key: 'kingsMe',
  text: `${KINGS_DOUBT} Подскажи: ты боролся в кингсмув?`,
  options: YES_NO,
  cols: 2,
  ack: (_, k) => ackMe(k) + CHECK,
  ackMore: (_, k) => ackMe(k),
};

// «хотя бы часть схватки»: кингсмув 10 с, а дожал перестройкой в трицепс — спортсмен отметит трицепс (эксперт)
const OPP_TEXT = 'боролся в кингсмув хотя бы часть схватки — даже если дожал другой техникой?';
export const Q_KINGS_OPP: Question = {
  key: 'kingsOpp',
  text: `${KINGS_DOUBT} Подскажи: соперник ${OPP_TEXT}`,
  options: YES_NO,
  cols: 2,
  ack: (_, k) => ackOpp(k) + CHECK,
  ackMore: (_, k) => ackOpp(k),
};

/** Вопросы про кингсмув по списку сервера: сначала про себя, затем про соперника — уже без повтора оговорки. */
export function kingsQuestions(keys: KingsQuestion[]): Question[] {
  const both = keys.includes('kingsMe') && keys.includes('kingsOpp');
  return [
    ...(keys.includes('kingsMe') ? [Q_KINGS_ME] : []),
    ...(keys.includes('kingsOpp') ? [both ? { ...Q_KINGS_OPP, text: `А соперник? Он ${OPP_TEXT}` } : Q_KINGS_OPP] : []),
  ];
}

